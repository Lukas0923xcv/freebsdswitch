package plan

import (
	"fmt"
	"sort"
	"strings"

	"github.com/Lukas0923xcv/freebsdswitch/internal/backend"
	"github.com/Lukas0923xcv/freebsdswitch/internal/config"
)

// PFConfPath is where the generated ruleset is written.
const PFConfPath = "/usr/local/etc/bsdswitch/pf.conf"

// FilteringEnabled reports whether pf must see bridged traffic.
func FilteringEnabled(c *config.Config) bool {
	if len(c.ACLs) > 0 {
		return true
	}
	for _, r := range c.RateLimits {
		if r.Ingress > 0 || r.Egress > 0 {
			return true
		}
	}
	return false
}

// pipeNumbers assigns dummynet pipe numbers: port index*2+1 (in), +2 (out).
func pipeNumbers(c *config.Config) map[string][2]int {
	out := map[string][2]int{}
	for i, r := range c.RateLimits {
		var p [2]int
		if r.Ingress > 0 {
			p[0] = 1000 + i*2 + 1
		}
		if r.Egress > 0 {
			p[1] = 1000 + i*2 + 2
		}
		out[r.Port] = p
	}
	return out
}

// DnctlOps returns the dummynet pipe configuration commands.
func DnctlOps(c *config.Config) []backend.Op {
	var ops []backend.Op
	pipes := pipeNumbers(c)
	for _, r := range c.RateLimits {
		p := pipes[r.Port]
		if p[0] != 0 {
			ops = append(ops, backend.Exec("dnctl", "pipe", fmt.Sprint(p[0]), "config", "bw", fmt.Sprintf("%dKbit/s", r.Ingress)))
		}
		if p[1] != 0 {
			ops = append(ops, backend.Exec("dnctl", "pipe", fmt.Sprint(p[1]), "config", "bw", fmt.Sprintf("%dKbit/s", r.Egress)))
		}
	}
	return ops
}

func pfAddr(s string) string {
	if s == "" || s == "any" {
		return "any"
	}
	return s
}

// PFConf renders the pf ruleset for ACLs and rate limits ("" if neither
// is configured).
//
// pf sees bridged frames on the member ports (net.link.bridge.pfil_member=1):
// "in" is traffic entering the switch through the port, "out" is traffic
// leaving through it. Only untagged IP traffic is filtered: 802.1Q-tagged
// frames on trunk ports are not IP from pf's point of view and pass.
func PFConf(c *config.Config) string {
	if !FilteringEnabled(c) {
		return ""
	}
	var sb strings.Builder
	w := func(f string, a ...any) { fmt.Fprintf(&sb, f+"\n", a...) }
	w("# Generated by bsdswitch - do not edit. Changes are made in the web UI / config.yaml.")
	w("set skip on lo0")
	skip := []string{c.Management.Interface, c.Bridge.Name}
	if c.Management.InBand.Enabled {
		skip = append(skip, InBandName(c))
	}
	w("# management is never filtered by switch ACLs")
	w("set skip on { %s }", strings.Join(skip, " "))
	w("set block-policy drop")
	w("set state-policy if-bound")
	w("")
	pipes := pipeNumbers(c)
	dn := func(port, dir string) string {
		p := pipes[port]
		n := p[0]
		if dir == "out" {
			n = p[1]
		}
		if n == 0 {
			return ""
		}
		return fmt.Sprintf(" dnpipe %d", n)
	}
	acls := append([]config.ACL{}, c.ACLs...)
	sort.SliceStable(acls, func(i, j int) bool { return acls[i].Port < acls[j].Port })
	covered := map[string]bool{}
	for _, a := range acls {
		w("# ACL %s: %s on %s, default %s", a.Name, a.Direction, orAll(a.Port), a.Default)
		on := ""
		if a.Port != "" {
			on = " on " + a.Port
			covered[a.Port+"/"+a.Direction] = true
		}
		for _, r := range a.Rules {
			proto := ""
			if r.Proto != "" && r.Proto != "any" {
				proto = " proto " + r.Proto
			}
			port := ""
			if r.DstPort != "" {
				port = " port " + r.DstPort
			}
			act := "pass"
			state := " keep state"
			if r.Action == "block" {
				act, state = "block drop", ""
			}
			pipe := ""
			if act == "pass" && a.Port != "" {
				pipe = dn(a.Port, a.Direction)
			}
			cmt := ""
			if r.Comment != "" {
				cmt = fmt.Sprintf(" label \"%s\"", r.Comment)
			}
			w("%s %s quick%s%s from %s to %s%s%s%s%s", act, a.Direction, on, proto, pfAddr(r.Src), pfAddr(r.Dst), port, state, pipe, cmt)
		}
		if a.Default == "block" {
			w("block drop %s quick%s all", a.Direction, on)
		} else {
			pipe := ""
			if a.Port != "" {
				pipe = dn(a.Port, a.Direction)
			}
			w("pass %s quick%s all no state%s", a.Direction, on, pipe)
		}
		w("")
	}
	var rl []string
	for _, r := range c.RateLimits {
		for _, dir := range []string{"in", "out"} {
			if p := dn(r.Port, dir); p != "" && !covered[r.Port+"/"+dir] {
				rl = append(rl, fmt.Sprintf("pass %s quick on %s all no state%s", dir, r.Port, p))
			}
		}
	}
	if len(rl) > 0 {
		w("# rate limits (dummynet pipes, see dnctl pipe show)")
		for _, l := range rl {
			w("%s", l)
		}
		w("")
	}
	w("# everything else is switched normally")
	w("pass quick all no state")
	return sb.String()
}

func orAll(p string) string {
	if p == "" {
		return "all ports"
	}
	return p
}

// filters converges pf and dummynet. pf rules cannot be compared with the
// kernel cheaply, so the rendered ruleset of Prev is used to detect changes.
func (b *builder) filters() {
	c := b.in.Desired
	want := PFConf(c)
	prevWant := ""
	if b.in.Prev != nil {
		prevWant = PFConf(b.in.Prev)
		if want == prevWant && fmt.Sprint(DnctlOps(c)) == fmt.Sprint(DnctlOps(b.in.Prev)) {
			return
		}
	}
	b.section("Packet filter (ACLs and rate limits)")
	if want == "" {
		if b.in.Prev == nil || prevWant == "" {
			return
		}
		b.op(backend.Op{Path: PFConfPath, Content: "# Generated by bsdswitch: no ACLs or rate limits configured\npass quick all no state\n"})
		b.bestEffort("pfctl", "-f", PFConfPath)
		b.bestEffort("pfctl", "-d")
		b.bestEffort("dnctl", "-q", "flush")
		return
	}
	b.exec("kldload", "-n", "pf")
	dnops := DnctlOps(c)
	if len(dnops) > 0 {
		b.exec("kldload", "-n", "dummynet")
		b.bestEffort("dnctl", "-q", "flush")
		for _, o := range dnops {
			b.op(o)
		}
	}
	b.op(backend.Op{Path: PFConfPath, Content: want})
	b.exec("pfctl", "-f", PFConfPath)
	b.bestEffort("pfctl", "-e") // fails harmlessly when already enabled
}
